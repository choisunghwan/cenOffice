CREATE TABLE IF NOT EXISTS hub_skills (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(64)   NOT NULL,
    description           VARCHAR(1000) NOT NULL,
    category              VARCHAR(32)   NOT NULL,
    icon                  VARCHAR(16),
    visibility            VARCHAR(16)   NOT NULL,
    team                  VARCHAR(64),
    status                VARCHAR(24)   NOT NULL,
    owner                 VARCHAR(64)   NOT NULL,
    published_version_id  BIGINT,
    sample                BOOLEAN       NOT NULL,
    created_by            VARCHAR(64)   NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by            VARCHAR(64)   NOT NULL,
    updated_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_hub_skills_name UNIQUE (name)
);
CREATE INDEX IF NOT EXISTS ix_hub_skills_status ON hub_skills (status);
CREATE INDEX IF NOT EXISTS ix_hub_skills_owner  ON hub_skills (owner);

CREATE TABLE IF NOT EXISTS hub_skill_versions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id      BIGINT         NOT NULL,
    version       VARCHAR(32)    NOT NULL,
    status        VARCHAR(24)    NOT NULL,
    frontmatter   VARCHAR(4000),
    skill_md      VARCHAR(100000) NOT NULL,
    file_list     VARCHAR(4000),
    package_kind  VARCHAR(8)     NOT NULL,
    package_data  BYTEA,
    sha256        VARCHAR(64)    NOT NULL,
    risk_flags    VARCHAR(2000),
    created_by    VARCHAR(64)    NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_hub_skill_version UNIQUE (skill_id, version)
);
CREATE INDEX IF NOT EXISTS ix_hub_skill_versions_skill ON hub_skill_versions (skill_id);

CREATE TABLE IF NOT EXISTS hub_skill_tags (
    skill_id  BIGINT      NOT NULL,
    tag       VARCHAR(32) NOT NULL,
    PRIMARY KEY (skill_id, tag)
);
CREATE INDEX IF NOT EXISTS ix_hub_skill_tags_tag ON hub_skill_tags (tag);

CREATE TABLE IF NOT EXISTS hub_skill_reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id    BIGINT       NOT NULL,
    reviewer    VARCHAR(64)  NOT NULL,
    rating      INT          NOT NULL,
    comment     VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_hub_review UNIQUE (skill_id, reviewer)
);

CREATE TABLE IF NOT EXISTS hub_approval_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_type  VARCHAR(8)   NOT NULL,
    target_id    BIGINT       NOT NULL,
    version_id   BIGINT,
    action       VARCHAR(24)  NOT NULL,
    actor        VARCHAR(64)  NOT NULL,
    comment      VARCHAR(500),
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_hub_approval_target ON hub_approval_history (target_type, target_id);

CREATE TABLE IF NOT EXISTS hub_agents (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(64)   NOT NULL,
    description VARCHAR(1000) NOT NULL,
    duties      VARCHAR(1000),
    config      VARCHAR(4000),
    visibility  VARCHAR(16)   NOT NULL,
    team        VARCHAR(64),
    status      VARCHAR(24)   NOT NULL,
    owner       VARCHAR(64)   NOT NULL,
    version     INT           NOT NULL,
    sample      BOOLEAN       NOT NULL,
    created_by  VARCHAR(64)   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_by  VARCHAR(64)   NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_hub_agents_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS hub_agent_versions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_id    BIGINT        NOT NULL,
    version     INT           NOT NULL,
    snapshot    VARCHAR(8000) NOT NULL,
    created_by  VARCHAR(64)   NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_hub_agent_version UNIQUE (agent_id, version)
);

CREATE TABLE IF NOT EXISTS hub_agent_skills (
    agent_id  BIGINT NOT NULL,
    skill_id  BIGINT NOT NULL,
    sort_order INT   NOT NULL,
    PRIMARY KEY (agent_id, skill_id)
);

CREATE TABLE IF NOT EXISTS hub_executions (
    id                VARCHAR(36)  NOT NULL PRIMARY KEY,
    target_type       VARCHAR(8)   NOT NULL,
    skill_id          BIGINT,
    skill_version_id  BIGINT,
    agent_id          BIGINT,
    requester         VARCHAR(64)  NOT NULL,
    input_hash        VARCHAR(64)  NOT NULL,
    input             VARCHAR(4000),
    status            VARCHAR(16)  NOT NULL,
    runtime_kind      VARCHAR(16)  NOT NULL,
    simulated         BOOLEAN      NOT NULL,
    counted           BOOLEAN      NOT NULL,
    result            VARCHAR(20000),
    error             VARCHAR(500),
    external_id       VARCHAR(64),
    requested_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    started_at        TIMESTAMP WITH TIME ZONE,
    completed_at      TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_hub_exec_skill     ON hub_executions (skill_id, requested_at);
CREATE INDEX IF NOT EXISTS ix_hub_exec_requester ON hub_executions (requester, requested_at);

CREATE TABLE IF NOT EXISTS hub_usage_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id      BIGINT       NOT NULL,
    version_id    BIGINT,
    agent_id      BIGINT,
    actor         VARCHAR(64)  NOT NULL,
    type          VARCHAR(24)  NOT NULL,
    execution_id  VARCHAR(36),
    counted       BOOLEAN      NOT NULL,
    occurred_at   TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_hub_usage_exec_type UNIQUE (execution_id, skill_id, type)
);
CREATE INDEX IF NOT EXISTS ix_hub_usage_skill ON hub_usage_events (skill_id, occurred_at);
