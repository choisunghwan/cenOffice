-- 이메일 알림 발송 대기열. 알림 저장과 같은 트랜잭션에서 쌓고, 별도 작업이 SMTP 로 보낸다.
-- 메일 서버가 느리거나 죽어도 회의록 확정 같은 본 작업은 실패하지 않는다. 실패는 last_error 에 남고 몇 번 재시도한다.
-- (users.email / users.email_notify 칸은 users 테이블을 관리하는 Hibernate 가 UserAccount 엔티티 기준으로 추가한다.)
CREATE TABLE email_outbox (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(64)  NOT NULL,
    to_email        VARCHAR(254) NOT NULL,
    kind            VARCHAR(32)  NOT NULL,
    subject         VARCHAR(300) NOT NULL,
    body            TEXT         NOT NULL,
    status          VARCHAR(12)  NOT NULL,
    attempts        INT          NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_error      VARCHAR(500),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at         TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_email_outbox_due ON email_outbox(status, next_attempt_at);
CREATE INDEX ix_email_outbox_user ON email_outbox(username, id);
