-- 예전에는 Hibernate(ddl-auto=update)가 자동으로 만들던 테이블을 Flyway 기록으로 옮긴다.
-- 이미 있는 DB(운영·개발)에서는 아무것도 바꾸지 않는다(IF NOT EXISTS). 새 DB에서는 이 파일이 테이블을 만든다.
-- 이 뒤로 ddl-auto 는 validate 이며, 테이블 구조 변경은 새 V번호 파일로만 한다.
-- 열 이름·길이·제약은 실제 PostgreSQL 운영 DB 에서 읽은 값과 같다(2026-10-29 대조).

CREATE TABLE IF NOT EXISTS users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username         VARCHAR(64)  NOT NULL,
    display_name     VARCHAR(100) NOT NULL,
    password_hash    VARCHAR(255) NOT NULL,
    role             VARCHAR(16)  NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    team             VARCHAR(64),
    email            VARCHAR(254),
    email_notify     BOOLEAN,
    calendar_manager BOOLEAN,
    CONSTRAINT uk_users_username UNIQUE (username)
);

CREATE TABLE IF NOT EXISTS devices (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code           VARCHAR(64)   NOT NULL,
    name           VARCHAR(100)  NOT NULL,
    type           VARCHAR(24)   NOT NULL CHECK (type IN ('LIGHT', 'AIR_CONDITIONER')),
    adapter_type   VARCHAR(16)   NOT NULL CHECK (adapter_type IN ('MOCK', 'MQTT', 'HTTP')),
    adapter_config VARCHAR(1000),
    object_id      VARCHAR(64),
    CONSTRAINT uk_devices_code UNIQUE (code)
);

CREATE TABLE IF NOT EXISTS device_states (
    device_id    BIGINT NOT NULL PRIMARY KEY,
    online       BOOLEAN NOT NULL,
    power        BOOLEAN NOT NULL,
    target_temp  DOUBLE PRECISION,
    current_temp DOUBLE PRECISION,
    ac_mode      VARCHAR(16),
    updated_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS device_commands (
    id           UUID NOT NULL PRIMARY KEY,
    device_id    BIGINT NOT NULL,
    requested_by VARCHAR(64) NOT NULL,
    status       VARCHAR(16) NOT NULL CHECK (status IN ('REQUESTED', 'SENT', 'CONFIRMED', 'FAILED', 'TIMEOUT')),
    power        BOOLEAN,
    target_temp  DOUBLE PRECISION,
    ac_mode      VARCHAR(16),
    error        VARCHAR(500),
    requested_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    sent_at      TIMESTAMP(6) WITH TIME ZONE,
    completed_at TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idxhw4nnctlplb1eaooghv5f45l7 ON device_commands (device_id, requested_at);

CREATE TABLE IF NOT EXISTS meeting_rooms (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(100) NOT NULL,
    capacity INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS reservations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT NOT NULL,
    title       VARCHAR(200) NOT NULL,
    reserved_by VARCHAR(64) NOT NULL,
    start_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    end_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idxqg7bfhe2ahd2wmxhr6s98mlk8 ON reservations (room_id, start_at);

CREATE TABLE IF NOT EXISTS audit_logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor      VARCHAR(64) NOT NULL,
    action     VARCHAR(64) NOT NULL,
    target     VARCHAR(128),
    detail     VARCHAR(1000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS offices (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS chat_rooms (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    office_id  BIGINT NOT NULL,
    room_key   VARCHAR(200) NOT NULL,
    type       VARCHAR(16) NOT NULL CHECK (type IN ('OFFICE', 'DIRECT', 'AI')),
    name       VARCHAR(100),
    agent_code VARCHAR(32),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_chat_rooms_room_key UNIQUE (room_key)
);

CREATE TABLE IF NOT EXISTS chat_room_members (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id  BIGINT NOT NULL,
    username VARCHAR(64) NOT NULL,
    CONSTRAINT uk_chat_room_members UNIQUE (room_id, username)
);

CREATE TABLE IF NOT EXISTS chat_messages (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id     BIGINT NOT NULL,
    sender_type VARCHAR(8) NOT NULL CHECK (sender_type IN ('USER', 'AI')),
    sender      VARCHAR(64) NOT NULL,
    sender_name VARCHAR(100) NOT NULL,
    content     VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idxlsxym2lfecnutuyap876203iy ON chat_messages (room_id, id);

CREATE TABLE IF NOT EXISTS ai_agents (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(32) NOT NULL,
    name                 VARCHAR(64) NOT NULL,
    role                 VARCHAR(16) NOT NULL CHECK (role IN ('PM', 'DEV', 'QA')),
    enabled              BOOLEAN NOT NULL,
    allowed_environments VARCHAR(32) NOT NULL,
    CONSTRAINT uk_ai_agents_code UNIQUE (code)
);
