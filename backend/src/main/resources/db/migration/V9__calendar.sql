-- 달력 일정. 전체(SHARED: 회사 공통, 관리자·일정 관리자만 등록)와 개인(PERSONAL: 본인 + 초대받은 사람에게 보임).
-- 회의실 예약(reservations)과 회의록 할 일 기한(meeting_action_items)은 이 테이블에 복사하지 않고 조회할 때 합쳐서 보여 준다.
-- (users.calendar_manager 칸은 users 테이블을 관리하는 Hibernate 가 UserAccount 엔티티 기준으로 추가한다.)
CREATE TABLE calendar_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope       VARCHAR(8)   NOT NULL,
    title       VARCHAR(200) NOT NULL,
    description VARCHAR(2000),
    location    VARCHAR(200),
    start_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    all_day     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_by  VARCHAR(64)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_calendar_events_scope_start ON calendar_events(scope, start_at);
CREATE INDEX ix_calendar_events_creator ON calendar_events(created_by);

CREATE TABLE calendar_attendees (
    event_id BIGINT      NOT NULL REFERENCES calendar_events(id) ON DELETE CASCADE,
    username VARCHAR(64) NOT NULL,
    PRIMARY KEY (event_id, username)
);
CREATE INDEX ix_calendar_attendees_user ON calendar_attendees(username);
