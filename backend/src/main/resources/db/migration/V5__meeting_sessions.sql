CREATE TABLE collaboration_meetings (
    id VARCHAR(36) PRIMARY KEY,
    title VARCHAR(120) NOT NULL,
    host_username VARCHAR(64) NOT NULL,
    join_code VARCHAR(32) NOT NULL UNIQUE,
    state VARCHAR(16) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    ended_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE collaboration_members (
    meeting_id VARCHAR(36) NOT NULL REFERENCES collaboration_meetings(id),
    username VARCHAR(64) NOT NULL,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(meeting_id, username)
);
CREATE INDEX ix_collaboration_member_user ON collaboration_members(username);
CREATE TABLE collaboration_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id VARCHAR(36) NOT NULL REFERENCES collaboration_meetings(id),
    username VARCHAR(64) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    content VARCHAR(1000) NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_collaboration_messages ON collaboration_messages(meeting_id, id);
