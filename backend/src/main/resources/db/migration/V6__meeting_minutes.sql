-- 회의록(초안/확정), 액션 아이템, 시스템 알림. 회의 테이블(V5)을 참조하며 기존 테이블은 변경하지 않는다.
CREATE TABLE meeting_minutes (
    meeting_id       VARCHAR(36) PRIMARY KEY REFERENCES collaboration_meetings(id),
    status           VARCHAR(16) NOT NULL,
    summary          TEXT NOT NULL,
    decisions        TEXT NOT NULL,
    issues           TEXT NOT NULL,
    extra_notes      VARCHAR(4000),
    source           VARCHAR(80) NOT NULL,
    generated_by     VARCHAR(64) NOT NULL,
    generated_at     TIMESTAMP WITH TIME ZONE NOT NULL,
    generation_count INT NOT NULL,
    confirmed_by     VARCHAR(64),
    confirmed_at     TIMESTAMP WITH TIME ZONE
);

CREATE TABLE meeting_action_items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id        VARCHAR(36) NOT NULL REFERENCES collaboration_meetings(id),
    position          INT NOT NULL,
    content           VARCHAR(500) NOT NULL,
    assignee_username VARCHAR(64),
    assignee_text     VARCHAR(100),
    due_text          VARCHAR(60),
    done              BOOLEAN NOT NULL DEFAULT FALSE,
    done_at           TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_action_items_meeting ON meeting_action_items(meeting_id, position);
CREATE INDEX ix_action_items_assignee ON meeting_action_items(assignee_username);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   VARCHAR(64) NOT NULL,
    type       VARCHAR(32) NOT NULL,
    title      VARCHAR(200) NOT NULL,
    body       VARCHAR(1000),
    link       VARCHAR(100),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at    TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_notifications_user ON notifications(username, id);
