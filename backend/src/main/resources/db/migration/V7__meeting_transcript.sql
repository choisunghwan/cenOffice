-- 회의 음성 인식(STT) 전문. 오디오는 저장하지 않고 변환된 텍스트만 저장한다.
-- 참석자별 동의(meeting_stt_consent)가 있어야 그 사람의 발언을 기록할 수 있다.
CREATE TABLE meeting_stt_consent (
    meeting_id   VARCHAR(36) NOT NULL REFERENCES collaboration_meetings(id),
    username     VARCHAR(64) NOT NULL,
    engine       VARCHAR(40) NOT NULL,
    consented_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY(meeting_id, username)
);
CREATE TABLE meeting_transcript (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meeting_id   VARCHAR(36) NOT NULL REFERENCES collaboration_meetings(id),
    username     VARCHAR(64) NOT NULL,
    display_name VARCHAR(100) NOT NULL,
    content      VARCHAR(600) NOT NULL,
    engine       VARCHAR(40) NOT NULL,
    spoken_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_meeting_transcript ON meeting_transcript(meeting_id, id);
