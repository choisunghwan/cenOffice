-- 개인 액세스 토큰 (MCP 등 외부 AI 도구 연동용). 토큰 원문은 저장하지 않고 SHA-256 해시만 저장한다.
CREATE TABLE IF NOT EXISTS hub_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner         VARCHAR(64)  NOT NULL,
    name          VARCHAR(64)  NOT NULL,
    token_hash    VARCHAR(64)  NOT NULL,
    token_prefix  VARCHAR(16)  NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    expires_at    TIMESTAMP    NOT NULL,
    last_used_at  TIMESTAMP,
    revoked       BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_hub_tokens_hash ON hub_tokens (token_hash);
CREATE INDEX IF NOT EXISTS ix_hub_tokens_owner ON hub_tokens (owner);
